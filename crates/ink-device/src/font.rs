//! A 5x8 bitmap font (ASCII 32..126) for text the device layer draws itself: the USB
//! lock screen, the fallback screensaver and the `rinky device` test screens.
//! The app's real text goes through `ink-text`; this exists because `ink-device`
//! cannot depend on it.
//!
//! Each glyph is 5 column bytes, bit 0 = top row (the classic "glcdfont" layout).
//! A cell is 6 x 9 font pixels (one column and one row of spacing), scaled by `scale`.

use crate::canvas::Canvas;

