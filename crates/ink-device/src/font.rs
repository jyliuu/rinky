fn glyph(c: char) -> [u8; 5] {
    let i = c as u32;
    if (32..127).contains(&i) {
        GLYPHS[(i - 32) as usize]
    } else {
        GLYPHS[('?' as u32 - 32) as usize]
    }
}

/// Width in pixels of `text` at `scale`.
pub fn text_width(text: &str, scale: i32) -> i32 {
    text.chars().count() as i32 * CELL_W * scale
}

/// Draws `text` with its top-left corner at `(x, y)` in gray `value`.
pub fn draw_text(canvas: &mut Canvas, x: i32, y: i32, scale: i32, value: u8, text: &str) {
    let scale = scale.max(1);
    for (i, c) in text.chars().enumerate() {
        let gx = x + i as i32 * CELL_W * scale;
        for (col, bits) in glyph(c).iter().enumerate() {
            for row in 0..8 {
                if bits & (1 << row) != 0 {
                    canvas.fill_rect(gx + col as i32 * scale, y + row * scale, scale, scale, value);
                }
            }
        }
    }
}

/// Draws `text` centred horizontally at row `y`.
pub fn draw_centered(canvas: &mut Canvas, y: i32, scale: i32, value: u8, text: &str) {
    let x = (canvas.width as i32 - text_width(text, scale)) / 2;
    draw_text(canvas, x, y, scale, value, text);
}

/// Free space kept on each side by [`draw_lines_centered`] (the message screens have a
/// 40-pixel frame).
pub const SIDE_MARGIN: i32 = 80;

/// Draws lines centred on the canvas (white background is not cleared). A line wider
/// than the canvas minus [`SIDE_MARGIN`] on both sides is drawn smaller.
pub fn draw_lines_centered(canvas: &mut Canvas, scale: i32, value: u8, lines: &[&str]) {
    let line_h = CELL_H * scale + scale * 4;
    let total = line_h * lines.len() as i32;
    let mut y = (canvas.height as i32 - total) / 2;
    for l in lines {
        // Shrink a line that would not fit.
        let mut s = scale;
        while s > 1 && text_width(l, s) > canvas.width as i32 - 2 * SIDE_MARGIN {
            s -= 1;
        }
        draw_centered(canvas, y, s, value, l);
        y += line_h;
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn draws_ink_inside_the_cell() {
        let mut c = Canvas::new(100, 40);
        draw_text(&mut c, 2, 3, 2, 0, "I");
        // 'I' has its stem in column 2: x = 2 + 2*2 .. +2, rows 0..7.
        assert_eq!(c.get(2 + 4, 3 + 6), Some(0));
        assert_eq!(c.get(2, 3), Some(255));
        assert_eq!(text_width("abc", 3), 54);
        let mut d = Canvas::new(200, 200);
        draw_lines_centered(&mut d, 4, 0, &["USB", "drive mode"]);
        assert!(d.pixels.contains(&0));
        // Non-ASCII falls back to '?' without panicking.
        draw_text(&mut d, 0, 0, 1, 0, "é€");
    }

    #[test]
    fn long_lines_stay_inside_the_side_margins() {
        // The USB lock screen line that touched the frame on the 1272-pixel panel.
        let mut c = Canvas::new(1272, 400);
        c.clear(255);
        draw_lines_centered(&mut c, 8, 0, &["Eject it on the computer,"]);
        for y in 0..400 {
            for x in (0..SIDE_MARGIN).chain(1272 - SIDE_MARGIN..1272) {
                assert_eq!(c.get(x, y), Some(255), "ink at {x},{y}");
            }
        }
        assert!(c.pixels.contains(&0));
    }
}
